const now = new Date()
const hoursAgo = (hours: number) => new Date(now.getTime() - hours * 3600000).toISOString()
const daysAgo = (days: number) => new Date(now.getTime() - days * 86400000).toISOString()
const hoursFromNow = (hours: number) => new Date(now.getTime() + hours * 3600000).toISOString()

const createTimelineEvent = (
  id: string,
  rfqId: string,
  type: RFQTimelineEvent['type'],
  title: string,
  timestamp: string,
  options: Partial<RFQTimelineEvent> = {}
): RFQTimelineEvent => ({
  id,
  rfqId,
  type,
  title,
  timestamp,
  ...options,
})

const createDocument = (
  id: string,
  rfqId: string,
  name: string,
  type: RFQDocument['type'],
  size: number,
  uploadedAt: string
): RFQDocument => ({
  id,
  rfqId,
  name,
  type,
  size,
  url: `/documents/${id}`,
  uploadedAt,
  ocrProcessed: type !== 'pdf',
  ocrConfidence: type !== 'pdf' ? 0.92 : undefined,
})

const createVendorRecommendation = (
  id: string,
  rfqId: string,
  vendorName: string,
  vendorLocation: string,
  score: number,
  confidence: AIVendorRecommendation['confidence'],
  matchReasons: string[]
): AIVendorRecommendation => ({
  id,
  rfqId,
  vendorId: `v-${id}`,
  vendorName,
  vendorLocation,
  score,
  confidence,
  matchReasons,
  historicalPerformance: {
    onTimeDeliveryRate: 85 + Math.random() * 14,
    qualityScore: 88 + Math.random() * 10,
    responseRate: 90 + Math.random() * 8,
    averageLeadTime: 3 + Math.floor(Math.random() * 5),
  },
  pricingHistory: {
    averagePrice: 42000 + Math.random() * 8000,
    marketAverage: 45000,
    competitivenessScore: 70 + Math.random() * 25,
  },
  regionCompatibility: vendorLocation.includes('Hyderabad') || vendorLocation.includes('Secunderabad') ? 'exact' : 'near',
})

const createItem = (
  id: string,
  rfqId: string,
  material: string,
  quantity: number,
  unit: string
): RFQItem => ({
  id,
  rfqId,
  materialDescription: material,
  quantity,
  unit,
  requiredDate: hoursFromNow(72 + Math.random() * 120),
  deliveryLocation: 'Hyderabad',
})

const createRequirement = (
  id: string,
  rfqId: string,
  category: RFQRequirement['category'],
  label: string,
  value: string,
  confidence: number,
  validationStatus: RFQRequirement['validationStatus']
): RFQRequirement => ({
  id,
  rfqId,
  category,
  label,
  value,
  confidence,
  validationStatus,
})

